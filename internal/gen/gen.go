// Package gen turns a manifest into the go.mod and main.go of the plugin
// binary. The binary is an ordinary Go program that imports the extension
// packages and registers them by name; the Go toolchain does the rest
// (module resolution, checksum verification, build cache).
//
// Every transport is linked in and chosen at run time with --transport, so one
// binary serves Neovim, Vim and the dev/test jsonl transport alike.
package gen

import (
	"fmt"
	"go/format"
	"path/filepath"
	"slices"
	"sort"
	"strconv"
	"strings"

	"github.com/Shougo/goda.vim/internal/manifest"
)

// Transports lists the editor transports linked into every plugin binary. The
// import path is <goda module>/host/<name> and the package name equals <name>.
var Transports = []string{"nvim", "vim", "jsonl"}

type requirement struct{ version, replace string }

// Render returns go.mod and main.go. baseDir is the manifest's directory;
// relative replace paths are resolved against it. defaultTransport is what the
// binary uses when run without --transport.
func Render(m *manifest.Manifest, baseDir, defaultTransport string) (goMod, mainGo string, err error) {
	if !slices.Contains(Transports, defaultTransport) {
		return "", "", fmt.Errorf("unknown transport %q (want %s)", defaultTransport, strings.Join(Transports, ", "))
	}

	reqs := map[string]requirement{
		m.Goda.Module: {m.Goda.Version, resolve(baseDir, m.Goda.Replace)},
	}
	for _, e := range m.Exts {
		if e.Module == m.Goda.Module {
			continue
		}
		r := requirement{e.Version, resolve(baseDir, e.Replace)}
		if r.version == "" {
			if r.replace == "" {
				return "", "", fmt.Errorf("line %d: %s %q needs a version (or a replace for local development)", e.Line, e.Kind, e.Name)
			}
			r.version = manifest.DefaultVersion
		}
		if prev, dup := reqs[e.Module]; dup && prev != r {
			return "", "", fmt.Errorf("line %d: module %s is required twice with different version/replace", e.Line, e.Module)
		}
		reqs[e.Module] = r
	}

	mods := make([]string, 0, len(reqs))
	for mod := range reqs {
		mods = append(mods, mod)
	}
	sort.Strings(mods)

	var mb strings.Builder
	mb.WriteString("// Code generated by goda-build; DO NOT EDIT.\n\nmodule goda-host\n\ngo 1.24\n\nrequire (\n")
	for _, mod := range mods {
		fmt.Fprintf(&mb, "\t%s %s\n", mod, reqs[mod].version)
	}
	mb.WriteString(")\n")
	var replaces []string
	for _, mod := range mods {
		if p := reqs[mod].replace; p != "" {
			replaces = append(replaces, fmt.Sprintf("\t%s => %s\n", mod, strconv.Quote(filepath.ToSlash(p))))
		}
	}
	if len(replaces) > 0 {
		mb.WriteString("\nreplace (\n" + strings.Join(replaces, "") + ")\n")
	}

	var b strings.Builder
	b.WriteString("// Code generated by goda-build; DO NOT EDIT.\n\npackage main\n\nimport (\n")
	b.WriteString("\t\"flag\"\n\t\"fmt\"\n\t\"os\"\n\n")
	fmt.Fprintf(&b, "\t%q\n", m.Goda.Module+"/sdk")
	for _, t := range Transports {
		fmt.Fprintf(&b, "\t%q\n", m.Goda.Module+"/host/"+t)
	}
	for i, e := range m.Exts {
		fmt.Fprintf(&b, "\te%d %q\n", i, e.Package)
	}
	b.WriteString(")\n\nfunc main() {\n")
	fmt.Fprintf(&b, "\ttransport := flag.String(\"transport\", %q, %q)\n",
		defaultTransport, "editor transport: "+strings.Join(Transports, ", "))
	b.WriteString("\tflag.Parse()\n\n\treg := sdk.NewRegistry()\n")
	for i, e := range m.Exts {
		kind := "Source"
		if e.Kind == "filter" {
			kind = "Filter"
		}
		fmt.Fprintf(&b, "\treg.Register%s(%q, e%d.New())\n", kind, e.Name, i)
	}
	b.WriteString("\n\tvar err error\n\tswitch *transport {\n")
	for _, t := range Transports {
		fmt.Fprintf(&b, "\tcase %q:\n\t\terr = %s.Serve(reg)\n", t, t)
	}
	b.WriteString("\tdefault:\n\t\terr = fmt.Errorf(\"unknown transport %q\", *transport)\n\t}\n")
	b.WriteString("\tif err != nil {\n\t\tfmt.Fprintln(os.Stderr, \"goda:\", err)\n\t\tos.Exit(1)\n\t}\n}\n")

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", "", fmt.Errorf("generated main.go does not parse: %w", err)
	}
	return mb.String(), string(formatted), nil
}

func resolve(baseDir, p string) string {
	if p == "" {
		return ""
	}
	if filepath.IsAbs(p) {
		return filepath.Clean(p)
	}
	return filepath.Join(baseDir, p)
}
